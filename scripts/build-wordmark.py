"""Builds the "لمسة" wordmark as SVG outlines from the Reem Kufi font (one-time).

The header logo used to be live text in Reem Kufi 700. This turns the same glyphs into
an SVG, so the logo needs no web font. Arabic needs shaping (joined letter forms), so
the text is shaped with HarfBuzz, then the glyph outlines are drawn with fontTools from
the variable font instantiated at weight 700.

Run in a throwaway venv (not a project dependency):

    python -m venv .venv-wordmark
    .venv-wordmark/Scripts/python -m pip install fonttools==4.66.1 uharfbuzz==0.56.3 brotli==1.2.0
    .venv-wordmark/Scripts/python scripts/build-wordmark.py <ReemKufi.woff2 or .ttf>

Writes src/components/shared/wordmark.svg (reference) and wordmark-data.ts (used by the
component). The viewBox is the CSS line box of the text at line-height 1 (1 em high,
baseline where the browser puts it), so the SVG takes the exact place of the old text.
"""

from __future__ import annotations

import io
import json
import sys
from pathlib import Path

import uharfbuzz as hb
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

TEXT = "لمسة"
WEIGHT = 700
OUT_DIR = Path(__file__).resolve().parent.parent / "src" / "components" / "shared"


def main(font_path: str) -> None:
    font = TTFont(font_path)
    if "fvar" in font:
        font = instantiateVariableFont(font, {"wght": WEIGHT}, inplace=False)
    font.flavor = None  # woff2 -> plain sfnt for HarfBuzz
    buffer = io.BytesIO()
    font.save(buffer)
    data = buffer.getvalue()
    font = TTFont(io.BytesIO(data))

    hb_font = hb.Font(hb.Face(data))
    upem = font["head"].unitsPerEm
    hb_font.scale = (upem, upem)
    buf = hb.Buffer()
    buf.add_str(TEXT)
    buf.guess_segment_properties()
    hb.shape(hb_font, buf, {"kern": True, "liga": True})

    glyph_set = font.getGlyphSet()
    order = font.getGlyphOrder()
    ascent = font["hhea"].ascent
    descent = -font["hhea"].descent  # positive
    # CSS line box at line-height 1: height 1 em, half-leading split above and below.
    baseline = (upem + ascent - descent) / 2

    pen = SVGPathPen(glyph_set)
    x = 0
    for info, pos in zip(buf.glyph_infos, buf.glyph_positions):
        name = order[info.codepoint]
        # Flip y (font units go up, SVG goes down) and move to the baseline.
        transform = (1, 0, 0, -1, x + pos.x_offset, baseline - pos.y_offset)
        glyph_set[name].draw(TransformPen(pen, transform))
        x += pos.x_advance
    width = x
    path = pen.getCommands()

    view_box = f"0 0 {width} {upem}"
    svg = (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{view_box}" '
        f'fill="currentColor" role="img" aria-label="{TEXT}"><path d="{path}"/></svg>\n'
    )
    # LF line endings on every platform (repository rule).
    (OUT_DIR / "wordmark.svg").write_text(svg, encoding="utf-8", newline="\n")
    ts = (
        "// Generated by scripts/build-wordmark.py from Reem Kufi 700. Do not edit.\n"
        f"export const WORDMARK_VIEW_BOX = {json.dumps(view_box)};\n"
        f"export const WORDMARK_ASPECT = {width / upem!r};\n"
        f"export const WORDMARK_PATH =\n  {json.dumps(path)};\n"
    )
    (OUT_DIR / "wordmark-data.ts").write_text(ts, encoding="utf-8", newline="\n")
    print(f"advance {width} / {upem} upem (aspect {width / upem:.4f}), baseline {baseline}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit("usage: build-wordmark.py <ReemKufi.woff2|ttf>")
    main(sys.argv[1])
